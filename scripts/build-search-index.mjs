#!/usr/bin/env node
/**
 * Builds lib/search-data.ts — a static, client-side full-text index of every
 * mirrored doc in both locales:
 *   en → ./docs (canonical, copied from the repos)
 *   es → ./i18n/es/docs (translated)
 * Excludes _*.md. Regenerated automatically before `next build`
 * (see package.json "prebuild").
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALE_ROOTS = {
  en: path.join(root, "docs"),
  es: path.join(root, "i18n", "es", "docs"),
};
const OUT = path.join(root, "lib", "search-data.ts");

function walk(dir, base, out) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith("_") || name.startsWith(".")) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, base, out);
    else if (name.endsWith(".md")) out.push(path.relative(base, full).split(path.sep).join("/"));
  }
  return out;
}

function fold(s) {
  return s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

/** Strip markup/code fences and collapse whitespace, then ASCII-fold. */
function plain(source) {
  return fold(
    source
      .replace(/<style[\s\S]*?<\/style>/gi, " ")
      .replace(/<script[\s\S]*?<\/script>/gi, " ")
      .replace(/<[^>]+>/g, " ")
      .replace(/```[\s\S]*?```/g, " ")
      .replace(/`([^`]*)`/g, "$1 ")
      .replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1")
      .replace(/[#>*_~|]/g, " ")
      .replace(/\s+/g, " ")
      .trim()
  );
}

function titleOf(source) {
  const html = /<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(source);
  const md = /^\s*#\s+(.+)$/m.exec(source);
  const raw = html ? html[1] : md ? md[1] : "";
  return plain(raw.replace(/<[^>]+>/g, "").replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")) || null;
}

function labelOf(repo, rel) {
  const inRepo = rel.slice(repo.length + 1);
  const isReadme = inRepo === "README.md" || inRepo.endsWith("/README.md");
  const pretty = isReadme
    ? inRepo.replace(/\/README\.md$/, "").replace(/^README\.md$/, "")
    : inRepo.replace(/\.md$/, "");
  return fold(pretty.replaceAll("/", " · ")).trim() || repo;
}

function collect(locale, docRoot) {
  const files = walk(docRoot, docRoot, []).sort();
  const out = [];
  for (const rel of files) {
    const source = readFileSync(path.join(docRoot, rel), "utf8");
    const seg = rel.split("/");
    const repo = seg[0];
    const inRepo = seg.slice(1).join("/");
    const isReadme = inRepo === "README.md" || inRepo.endsWith("/README.md");
    const slug = isReadme
      ? [repo, ...(inRepo === "README.md" ? [] : inRepo.split("/").slice(0, -1))]
      : [repo, ...inRepo.split("/").map((s) => s.replace(/\.md$/, ""))];
    out.push({
      locale,
      repo,
      title: titleOf(source) ?? labelOf(repo, rel).replaceAll(" · ", " "),
      label: labelOf(repo, rel),
      path: inRepo,
      slug,
      text: plain(source),
    });
  }
  return out;
}

const hits = [...collect("en", LOCALE_ROOTS.en), ...collect("es", LOCALE_ROOTS.es)];
const en = hits.filter((h) => h.locale === "en").length;
const es = hits.filter((h) => h.locale === "es").length;

const ts = `// AUTO-GENERATED by scripts/build-search-index.mjs — do not edit.
export interface DocHit {
  locale: "en" | "es";
  repo: string;
  title: string;
  label: string;
  path: string;
  slug: string[];
  text: string;
}

export const DOCS_INDEX: DocHit[] = ${JSON.stringify(hits)};
`;

writeFileSync(OUT, ts);
console.log(`search index: ${en} en + ${es} es → ${(Buffer.byteLength(ts) / 1024).toFixed(0)} KB`);
